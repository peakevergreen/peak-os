int main(void) {
    struct img_decoded img;
    memset(&img, 0, sizeof(img));
    expect(img_decode_ppm((const uint8_t *)ppm_ok, sizeof(ppm_ok) - 1, &img) == 0, "ppm parse");
    expect(img.w == 3 && img.h == 2, "ppm dims");
    expect(img.rgb && img.rgb[0] == 1 && img.rgb[5] == 6, "ppm pixels");
    img_decode_free(&img);

    memset(&img, 0, sizeof(img));
    expect(img_decode_bmp(bmp_ok, sizeof(bmp_ok), &img) == 0, "bmp parse");
    expect(img.w == 2 && img.h == 2, "bmp dims");
    expect(img.rgb && img.rgb[0] == 255 && img.rgb[1] == 0 && img.rgb[2] == 0, "bmp bgr->rgb");
    img_decode_free(&img);

    expect(img_decode_ppm((const uint8_t *)"P5\n1 1\n255\n0", 14, &img) != 0, "reject P5");
    expect(img_decode_bmp(bmp_ok, 10, &img) != 0, "reject short bmp");
    expect(img_decode_ppm((const uint8_t *)"P6\n9999 9999\n255\n", 18, &img) != 0,
           "reject huge ppm dims before alloc");
    expect(img_decode_ppm((const uint8_t *)"P6\n0 1\n255\n", 11, &img) != 0, "reject zero width");
    expect(img_decode_ppm((const uint8_t *)"P6\n800 800\n255\n", 15, &img) != 0,
           "reject ppm over pixel budget");
    {
        /* BMP BITMAPINFOHEADER claiming 2000x2000 24bpp — dims rejected before kmalloc */
        uint8_t huge_bmp[54];
        memset(huge_bmp, 0, sizeof(huge_bmp));
        huge_bmp[0] = 'B';
        huge_bmp[1] = 'M';
        huge_bmp[10] = 54;
        huge_bmp[14] = 40;
        huge_bmp[18] = 0xd0;
        huge_bmp[19] = 0x07; /* width 2000 */
        huge_bmp[22] = 0xd0;
        huge_bmp[23] = 0x07; /* height 2000 */
        huge_bmp[26] = 1;    /* planes */
        huge_bmp[28] = 24;   /* bpp */
        expect(img_decode_bmp(huge_bmp, sizeof(huge_bmp), &img) != 0,
               "reject huge bmp dims before alloc");
    }

    memset(&img, 0, sizeof(img));
    {
        const uint8_t stored[] = {0x01, 0x02, 0x00, 0xfd, 0xff, 0x41, 0x42};
        uint8_t raw[8];
        size_t rl = 0;
        expect(inflate_lite(stored, sizeof(stored), raw, sizeof(raw), &rl) == 0, "stored inflate");
        expect(rl == 2 && raw[0] == 'A' && raw[1] == 'B', "stored bytes");
    }
    {
        const uint8_t raw[] = {0x63, 0xf8, 0xcf, 0xc0, 0x00, 0x00};
        uint8_t buf[8];
        size_t rl = 0;
        expect(inflate_lite(raw, sizeof(raw), buf, sizeof(buf), &rl) == 0, "png raw deflate");
        expect(rl == 4 && buf[0] == 0 && buf[1] == 255 && buf[2] == 0 && buf[3] == 0, "png raw bytes");
    }
    {
        const uint8_t idat[] = {0x78,0x9c,0x63,0xf8,0xcf,0xc0,0x00,0x00,0x03,0x01,0x01,0x00};
        uint8_t raw[8];
        size_t rl = 0;
        expect(inflate_lite_zlib(idat, sizeof(idat), raw, sizeof(raw), &rl) == 0, "png idat inflate");
        expect(rl == 4 && raw[0] == 0 && raw[1] == 255 && raw[2] == 0 && raw[3] == 0, "png idat bytes");
    }
    expect(img_decode_png(png_1x1, sizeof(png_1x1), &img) == 0, "png 1x1 parse");
    expect(img.w == 1 && img.h == 1, "png 1x1 dims");
    expect(img.rgb && img.rgb[0] == 255 && img.rgb[1] == 0 && img.rgb[2] == 0, "png 1x1 red");
    img_decode_free(&img);

    memset(&img, 0, sizeof(img));
    expect(img_decode_jpeg(jpeg_1x1, sizeof(jpeg_1x1), &img) == 0, "jpeg 1x1 parse");
    expect(img.w == 1 && img.h == 1, "jpeg 1x1 dims");
    expect(img.rgb && img.rgb[0] >= 200 && img.rgb[1] <= 55 && img.rgb[2] <= 55, "jpeg 1x1 red");
    img_decode_free(&img);

    memset(&img, 0, sizeof(img));
    expect(img_decode_mem(png_1x1, sizeof(png_1x1), &img) == 0, "mem png autodetect");
    img_decode_free(&img);

    expect(img_decode_mem((const uint8_t *)"\x00\x01", 2, &img) != 0, "mem reject unknown");

    if (fails) {
        fprintf(stderr, "%d img_decode test(s) failed\n", fails);
        return 1;
    }
    printf("test_img_decode: ok\n");
    return 0;
}
